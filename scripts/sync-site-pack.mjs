// Copies each website pack's interview guide and example brief from the runner into the builder as a TypeScript file.
// The runner's vertical-packs/site (waitlist) and vertical-packs/saas are the single source. Run: npm run sync:site-pack
// RUNNER_DIR defaults to ../appnomics-runner.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const runner = path.resolve(process.env.RUNNER_DIR ?? "../appnomics-runner");
const read = (pack, f) => readFile(path.join(runner, "vertical-packs", pack, f), "utf8");
let out = "// Generated by scripts/sync-site-pack.mjs from the runner's vertical-packs. Do not edit by hand.\n";
for (const [pack, prefix] of [["site", "SITE"], ["saas", "SAAS"]]) {
  const interview = await read(pack, "interview.md");
  const example = JSON.stringify(JSON.parse(await read(pack, "brief.example.json")), null, 2);
  out += `export const ${prefix}_INTERVIEW_MD = ${JSON.stringify(interview)};\nexport const ${prefix}_EXAMPLE_BRIEF = ${JSON.stringify(example)};\n`;
}
await writeFile(path.resolve("src/lib/builder/site-pack.generated.ts"), out);
console.log(`Synced site and saas packs from ${runner}`);
