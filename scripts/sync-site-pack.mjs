// Copies the website interview guide and example brief from the runner into the builder as a TypeScript file.
// The runner's vertical-packs/site is the single source. Run: npm run sync:site-pack
// RUNNER_DIR defaults to ../appnomics-runner.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const runner = path.resolve(process.env.RUNNER_DIR ?? "../appnomics-runner");
const read = (f) => readFile(path.join(runner, "vertical-packs/site", f), "utf8");
const interview = await read("interview.md");
const example = JSON.stringify(JSON.parse(await read("brief.example.json")), null, 2);
const out = `// Generated by scripts/sync-site-pack.mjs from the runner's vertical-packs/site. Do not edit by hand.
export const SITE_INTERVIEW_MD = ${JSON.stringify(interview)};
export const SITE_EXAMPLE_BRIEF = ${JSON.stringify(example)};
`;
await writeFile(path.resolve("src/lib/builder/site-pack.generated.ts"), out);
console.log(`Synced site pack from ${runner}`);
